
package com.example.mobilesecurityanalyzer

import android.app.Activity
import android.os.Bundle
import android.graphics.Typeface
import android.view.Gravity
import android.view.View
import android.widget.Button
import android.widget.CheckBox
import android.widget.LinearLayout
import android.widget.ScrollView
import android.widget.TextView
import org.json.JSONObject
import org.json.JSONArray
import java.net.HttpURLConnection
import java.net.URL

class MainActivity : Activity() {

    private val permissionChecks = mutableMapOf<String, CheckBox>()
    private lateinit var resultView: TextView
    private lateinit var analyzeButton: Button

    private val permissionDescriptions = linkedMapOf(
        "CAMERA" to "Camera — photo/video capture",
        "RECORD_AUDIO" to "Microphone — audio recording",
        "ACCESS_FINE_LOCATION" to "Precise location",
        "READ_CONTACTS" to "Contacts access",
        "READ_SMS" to "SMS reading",
        "READ_CALL_LOG" to "Call history access",
        "READ_MEDIA_IMAGES" to "Photo/image access",
        "INTERNET" to "Internet access"
    )

    private val apiUrl =
        "https://ai-mobile-security-threat-analyzer-api.onrender.com/analyze"

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        val root = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(24, 24, 24, 24)
            setBackgroundColor(0xFFF6F8FC.toInt())
        }

        val scroll = ScrollView(this)
        val content = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(0, 0, 0, 12)
        }

        val title = TextView(this).apply {
            text = "AI Mobile Security\nThreat Analyzer"
            textSize = 25f
            setTypeface(null, Typeface.BOLD)
            setTextColor(0xFF172554.toInt())
        }
        content.addView(title)

        val intro = TextView(this).apply {
            text = "Select permissions to assess their potential security risk. Results are generated by the online analysis backend."
            textSize = 15f
            setPadding(0, 12, 0, 18)
            setTextColor(0xFF334155.toInt())
        }
        content.addView(intro)

        permissionDescriptions.forEach { (permission, label) ->
            val checkBox = CheckBox(this).apply {
                text = label
                textSize = 15f
            }
            permissionChecks[permission] = checkBox
            content.addView(checkBox)
        }

        analyzeButton = Button(this).apply {
            text = "Analyze Selected Permissions"
            setOnClickListener { analyzeSelection() }
        }
        content.addView(analyzeButton)

        resultView = TextView(this).apply {
            text = "Your analysis will appear here."
            textSize = 16f
            setTextColor(0xFF0F172A.toInt())
            setPadding(0, 20, 0, 20)
        }
        content.addView(resultView)

        val disclaimer = TextView(this).apply {
            text = "Important: Permission indicators alone cannot prove an app is malicious. This prototype does not automatically scan installed apps or inspect their behavior."
            textSize = 12f
            setTextColor(0xFF64748B.toInt())
            setPadding(0, 12, 0, 12)
        }
        content.addView(disclaimer)

        scroll.addView(content)
        root.addView(scroll)
        setContentView(root)
    }

    private fun analyzeSelection() {
        val selected = permissionChecks
            .filterValues { it.isChecked }
            .keys
            .toList()

        if (selected.isEmpty()) {
            resultView.text = "Select at least one permission, then tap Analyze."
            return
        }

        analyzeButton.isEnabled = false
        resultView.text = "Connecting to security analysis server...\nPlease wait."

        Thread {
            var connection: HttpURLConnection? = null

            try {
                connection = (URL(apiUrl).openConnection() as HttpURLConnection).apply {
                    requestMethod = "POST"
                    connectTimeout = 30000
                    readTimeout = 60000
                    doOutput = true
                    setRequestProperty(
                        "Content-Type",
                        "application/json; charset=UTF-8"
                    )
                    setRequestProperty("Accept", "application/json")
                }

                val requestBody = JSONObject().apply {
                    put("permissions", JSONArray(selected))
                }

                connection.outputStream.use { output ->
                    output.write(
                        requestBody.toString().toByteArray(Charsets.UTF_8)
                    )
                }

                val statusCode = connection.responseCode

                val responseStream = if (statusCode in 200..299) {
                    connection.inputStream
                } else {
                    connection.errorStream
                }

                val responseText = responseStream?.bufferedReader()?.use {
                    it.readText()
                } ?: throw Exception("The server returned an empty response.")

                if (statusCode !in 200..299) {
                    throw Exception("Server error: HTTP $statusCode")
                }

                val response = JSONObject(responseText)
                val score = response.getInt("risk_score")
                val level = response.getString("risk_level")
                val permissions = response.getJSONArray("permissions_analyzed")
                val findings = response.getJSONArray("findings")
                val disclaimerText = response.optString(
                    "disclaimer",
                    "Permission indicators alone do not prove malicious behavior."
                )

                val result = buildString {
                    append("Risk Indicator: $level\n")
                    append("Risk Score: $score / 100\n\n")
                    append("Permissions Analyzed:\n")

                    for (i in 0 until permissions.length()) {
                        append("• ${permissions.getString(i)}\n")
                    }

                    append("\nFindings:\n")

                    for (i in 0 until findings.length()) {
                        val finding = findings.getJSONObject(i)
                        append("• ${finding.getString("permission")}\n")
                        append("  Severity: ${finding.getString("severity")}\n")
                        append("  ${finding.getString("message")}\n\n")
                    }

                    append("Note: $disclaimerText")
                }

                runOnUiThread {
                    resultView.text = result
                }

            } catch (e: Exception) {
                runOnUiThread {
                    resultView.text =
                        "Analysis failed.\n\n" +
                        "${e.message ?: "Please try again."}\n\n" +
                        "Check your internet connection and try again."
                }
            } finally {
                connection?.disconnect()

                runOnUiThread {
                    analyzeButton.isEnabled = true
                }
            }
        }.start()
    }
}
